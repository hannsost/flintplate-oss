import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../lib/flintplate-labour.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { labourTimeChoices, resolveLabourTime, labourLocalTime } = await import(`data:text/javascript,${encodeURIComponent(compiled)}`);
assert.deepEqual(labourTimeChoices('2026-03-29T02:30', 'Europe/Berlin'), []);
assert.throws(() => resolveLabourTime('2026-03-29T02:30', 'Europe/Berlin', ''));
const autumn = labourTimeChoices('2026-10-25T02:30', 'Europe/Berlin');
assert.equal(autumn.length, 2);
assert.deepEqual(new Set(autumn.map(row => row.iso)), new Set(['2026-10-25T00:30:00.000Z', '2026-10-25T01:30:00.000Z']));
assert.throws(() => resolveLabourTime('2026-10-25T02:30', 'Europe/Berlin', ''));
assert.equal(resolveLabourTime('2026-10-25T02:30', 'Europe/Berlin', '2026-10-25T01:30:00.000Z'), '2026-10-25T01:30:00.000Z');
assert.equal(resolveLabourTime('2026-09-12T09:00', 'Europe/Berlin', ''), '2026-09-12T07:00:00.000Z');
assert.equal(labourLocalTime('2026-10-25T01:30:00Z', 'Europe/Berlin'), '2026-10-25T02:30');
assert.equal(resolveLabourTime('2026-09-12T09:00', 'Asia/Kathmandu', ''), '2026-09-12T03:15:00.000Z');
assert.equal(resolveLabourTime('2026-09-12T09:00', 'Europe/Berlin', '', '2026-09-12T07:00:45.123456Z'), '2026-09-12T07:00:45.123456Z');
assert.equal(resolveLabourTime('2026-10-25T02:30', 'Europe/Berlin', '2026-10-25T01:30:00.000Z', '2026-10-25T00:30:10Z'), '2026-10-25T01:30:00.000Z');
console.log('Labour dates: spring gap rejected, autumn ambiguity explicit, exact UTC and45-minute timezone preserved.');
